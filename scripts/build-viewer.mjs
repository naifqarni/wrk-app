// Builds the self-contained 3D viewer page (three.js + wrk. engine + product models + fonts) into one string module.
// Run: node scripts/build-viewer.mjs   (only needed after changing viewer-src/)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'viewer-src');
const read = (p) => fs.readFileSync(path.join(src, p), 'utf8');

/** Removes the `maker: { ... }` property (factory notes, never shipped to shoppers) from a product module. */
function stripMaker(code, file) {
  const m = /\n\s*maker:\s*\{/.exec(code);
  if (!m) return code;
  let i = m.index + m[0].length, depth = 1;
  while (i < code.length && depth > 0) {
    const c = code[i];
    if (c === '"' || c === "'" || c === '`') {
      const q = c; i++;
      while (i < code.length && code[i] !== q) { if (code[i] === '\\') i++; i++; }
    } else if (c === '/' && code[i + 1] === '/') { while (i < code.length && code[i] !== '\n') i++; continue; }
    else if (c === '/' && code[i + 1] === '*') { i = code.indexOf('*/', i + 2) + 1; }
    else if (c === '{') depth++;
    else if (c === '}') depth--;
    i++;
  }
  if (depth !== 0) throw new Error('unbalanced maker block in ' + file);
  let end = i;
  while (/\s/.test(code[end])) end++;
  if (code[end] === ',') end++;
  return code.slice(0, m.index) + code.slice(end);
}

const order = ['kit', 'badge', 'pen', 'notebook', 'card', 'cardcase', 'tray', 'nameplate'];
const products = order.map((id) => stripMaker(read(`products/${id}.js`), id));
for (const p of products) if (/unlisted|rfq:/.test(p)) throw new Error('maker data left in viewer');

const fontDir = path.join(root, 'node_modules/@expo-google-fonts');
const face = (family, weight, file) =>
  `@font-face{font-family:"${family}";font-weight:${weight};font-style:normal;src:url(data:font/ttf;base64,${fs.readFileSync(path.join(fontDir, file)).toString('base64')}) format("truetype")}`;
const fonts = [
  face('Jost', '200', 'jost/200ExtraLight/Jost_200ExtraLight.ttf'),
  face('Jost', '300 400', 'jost/300Light/Jost_300Light.ttf'),
  face('Alexandria', '200', 'alexandria/200ExtraLight/Alexandria_200ExtraLight.ttf'),
  face('Alexandria', '300 400', 'alexandria/300Light/Alexandria_300Light.ttf'),
  face('Readex Pro', '300 400', 'readex-pro/300Light/ReadexPro_300Light.ttf'),
].join('\n');

const safe = (js) => js.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html>
<html lang="ar" dir="rtl"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<style>
${fonts}
html,body{margin:0;height:100%;background:#F3F2EE;overflow:hidden;-webkit-user-select:none;user-select:none;-webkit-tap-highlight-color:transparent}
#stage{position:absolute;inset:0;background:radial-gradient(120% 100% at 30% 22%,#FAF9F6 0%,#E9E7E1 78%);cursor:grab;touch-action:pan-y}
#stage.is-dragging{cursor:grabbing}
</style></head><body><div id="stage"></div>
<script>${safe(read('vendor/three.min.js'))}</script>
<script>${safe(read('engine.js'))}</script>
${products.map((p) => `<script>${safe(p)}</script>`).join('\n')}
<script>${safe(read('boot.js'))}</script>
</body></html>`;

fs.mkdirSync(path.join(root, 'src/store/viewer'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/store/viewer/viewerHtml.ts'),
  `// Generated by scripts/build-viewer.mjs. Do not edit.\n/* eslint-disable */\nconst html: string = ${JSON.stringify(html)};\nexport default html;\n`);
console.log('viewer built:', (html.length / 1024 / 1024).toFixed(2), 'MB');
